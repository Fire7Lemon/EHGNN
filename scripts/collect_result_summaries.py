#!/usr/bin/env python3
"""Scan repository for results/**/summary.csv and summary.txt; write master index.

Output: <repo>/results/ALL_SUMMARIES_INDEX.md
Does not modify existing summaries."""
from __future__ import annotations

import datetime
from pathlib import Path


def main():
    root = Path(__file__).resolve().parent.parent
    out_dir = root / 'results'
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / 'ALL_SUMMARIES_INDEX.md'

    skip_substr = 'ALL_SUMMARIES_INDEX.md'

    csvs = sorted(
        p for p in root.rglob('summary.csv')
        if skip_substr not in str(p) and '.git' not in p.parts
    )
    txts = sorted(
        p for p in root.rglob('summary.txt')
        if skip_substr not in str(p) and '.git' not in p.parts
    )

    ts = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    lines = [
        '# ALL summaries index',
        '',
        'Auto-generated by `scripts/collect_result_summaries.py`.',
        'UTC time: {}'.format(ts),
        '',
        '## summary.csv ({})'.format(len(csvs)),
        '',
    ]
    for p in csvs:
        lines.append('- `{}`'.format(p.relative_to(root).as_posix()))
    lines.extend(['', '## summary.txt ({})'.format(len(txts)), ''])
    for p in txts:
        lines.append('- `{}`'.format(p.relative_to(root).as_posix()))
    lines.append('')

    text = '\n'.join(lines)
    out_path.write_text(text, encoding='utf-8')
    print('Wrote', out_path)


if __name__ == '__main__':
    main()
